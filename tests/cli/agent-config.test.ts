describe('discovery and lock file', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ai-guard-agent-config-'));
  const write = (rel: string, content: string): void => {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), content);
  };
  afterAll(() => fs.rmSync(root, { recursive: true, force: true }));

  write('CLAUDE.md', '# Guide\n');
  write('packages/web/AGENTS.md', 'Use pnpm.\n');
  write('.cursor/rules/style.mdc', 'Prefer named exports.\n');
  write('.github/copilot-instructions.md', 'Write tests.\n');
  write('.claude/commands/release.md', 'Bump the version.\n');
  write('.claude/settings.json', '{}');
  write('.vscode/mcp.json', '{ "servers": {} }');
  write('.mcp.json', JSON.stringify({ mcpServers: { gh: { command: 'npx', args: ['-y', '@acme/mcp@1.0.0'] } } }));
  write('tools/plugin/.claude-plugin/plugin.json', '{ "name": "p" }');
  write('tools/plugin/skills/check/SKILL.md', 'Run checks.\n');
  write('tools/plugin/hooks/hooks.json', '{ "hooks": {} }');
  write('src/hooks/hooks.json', '{}');
  write('node_modules/pkg/CLAUDE.md', 'ignored');
  write('docs/guide.md', 'not agent config');

  it('finds agent files and skips dependencies, unrelated docs and non-plugin hooks folders', () => {
    expect(discoverAgentConfigFiles(root)).toEqual([
      '.claude/commands/release.md',
      '.claude/settings.json',
      '.cursor/rules/style.mdc',
      '.github/copilot-instructions.md',
      '.mcp.json',
      '.vscode/mcp.json',
      'CLAUDE.md',
      'packages/web/AGENTS.md',
      'tools/plugin/hooks/hooks.json',
      'tools/plugin/skills/check/SKILL.md',
    ]);
  });

  it('classifies paths', () => {
    expect(classifyAgentConfigPath('.claude/settings.local.json')).toBe('claude-settings');
    expect(classifyAgentConfigPath('.cursor/mcp.json')).toBe('mcp-config');
    expect(classifyAgentConfigPath('README.md')).toBeNull();
    expect(classifyAgentConfigPath('src/hooks/hooks.json', root)).toBeNull();
    expect(classifyAgentConfigPath('tools/plugin/hooks/hooks.json', root)).toBe('plugin-hooks');
  });

  it('detects MCP servers that changed or were added after approval', () => {
    const first = scanAgentConfig({ root, updateLock: true });
    expect(first.lock.status).toBe('updated');
    expect(scanAgentConfig({ root }).findings).toEqual([]);

    write('.mcp.json', JSON.stringify({ mcpServers: {
      gh: { command: 'npx', args: ['-y', '@acme/mcp@1.0.1'] },
      extra: { command: 'node', args: ['x.js'] },
    } }));
    const report = scanAgentConfig({ root });
    expect(report.lock.status).toBe('checked');
    expect(checks(report.findings).sort()).toEqual(['mcp-server-changed', 'mcp-server-unapproved']);
  });
});

describe('scan-agent-config output', () => {
  const report = {
    root: path.resolve('/repo'),
    files: ['CLAUDE.md'],
    findings: [
      { check: 'hidden-text' as const, severity: 'error' as const, file: 'CLAUDE.md', line: 2, column: 1, message: 'Hidden text.', excerpt: 'x' },
      { check: 'concealment' as const, severity: 'warning' as const, file: 'CLAUDE.md', line: 3, column: 1, message: 'Hide.' },
    ],
    servers: [],
    errorCount: 1,
    warningCount: 1,
    durationMs: 1,
    lock: { file: '.ai-guard-mcp-lock.json', status: 'not-found' as const },
  };

  it('uses its own SARIF slot so uploads never replace the main scan', () => {
    const log = buildSarifLog(agentConfigToRunResult(report), '1.0.0', report.root, AGENT_CONFIG_AUTOMATION_ID);
    const run = log.runs[0];
    expect(run.automationDetails?.id).toBe('ai-guard-agent-config');
    expect(run.results.map((r) => [r.ruleId, r.level])).toEqual([
      ['ai-guard/agent-config/hidden-text', 'error'],
      ['ai-guard/agent-config/concealment', 'warning'],
    ]);
    expect(run.results[0].locations[0].physicalLocation.artifactLocation.uri).toBe('CLAUDE.md');
    expect(run.tool.driver.rules.map((r) => r.helpUri)).toEqual(expect.arrayContaining([expect.stringContaining('docs/cli/scan-agent-config.md#hidden-text')]));
  });

  it('leaves the main scan automation id unchanged by default', () => {
    expect(buildSarifLog(agentConfigToRunResult(report), '1.0.0', report.root).runs[0].automationDetails?.id).toBe('ai-guard');
  });

  it('maps --fail-on to exit codes', () => {
    expect(agentConfigExitCode(report, 'error')).toBe(1);
    expect(agentConfigExitCode(report, 'none')).toBe(0);
    const warningsOnly = { ...report, errorCount: 0, findings: [report.findings[1]] };
    expect(agentConfigExitCode(warningsOnly, 'error')).toBe(0);
    expect(agentConfigExitCode(warningsOnly, 'warning')).toBe(1);
  });
});
