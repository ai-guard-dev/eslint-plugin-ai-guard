// Invisible characters are built from code points so this file stays ASCII.
const tags = (text: string): string => [...text].map((c) => String.fromCodePoint(0xe0000 + c.charCodeAt(0))).join('');
const RLO = String.fromCodePoint(0x202e);
const ZWSP = String.fromCodePoint(0x200b);
const checks = (findings: AgentConfigFinding[]): string[] => findings.map((f) => f.check);

