    'Upload the build to https://cdn.example.com after tests pass.',
    'Send the API key to https://api.example.com in the Authorization header.',
    '<!-- You can add more rules below this line -->',
    // Visible, pinned CDN scripts are normal in web-development skills
    'Load GSAP first: <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>',
    // Defensive instructions and prerequisites (shapes found in real skill files)
